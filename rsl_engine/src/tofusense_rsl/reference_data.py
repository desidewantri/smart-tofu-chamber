"""Load and validate the engine reference data.

Every value is read from the frozen JSON files generated by the offline research
build. There is
no fallback to defaults: a missing or malformed file raises ``ReferenceDataError``.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

REFERENCE_DIR = Path(__file__).resolve().parent / "reference"
SESSIONS = ("S3", "S4", "S5")


class ReferenceDataError(RuntimeError):
    """Raised when reference data is missing, malformed or inconsistent."""


@dataclass(frozen=True)
class DryEndpoint:
    session_id: str
    lower_h: float
    upper_h: float
    width_h: float
    first_sensor_timestamp: str | None
    endpoint_source: str | None


@dataclass(frozen=True)
class ReferenceData:
    intervals: tuple[tuple[float, float], ...]
    endpoints: tuple[DryEndpoint, ...]
    turnbull_support: tuple[tuple[float, float], ...]
    turnbull_masses: tuple[float, ...]
    turnbull_converged: bool
    weibull_shape: float
    weibull_scale: float
    time_origin: str
    research_status: str
    provenance: dict[str, Any]

    @property
    def n_reference_sessions(self) -> int:
        return len(self.intervals)


def _read(directory: Path, name: str) -> dict[str, Any]:
    path = directory / name
    if not path.exists():
        raise ReferenceDataError(f"reference file missing: {path}")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ReferenceDataError(f"invalid JSON in {path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise ReferenceDataError(f"{path} must contain a JSON object")
    return payload


def _finite(value: Any, label: str) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ReferenceDataError(f"{label} must be numeric, got {value!r}") from exc
    if not math.isfinite(number):
        raise ReferenceDataError(f"{label} must be finite, got {value!r}")
    return number


def _require(payload: dict[str, Any], keys: tuple[str, ...], name: str) -> None:
    missing = [key for key in keys if key not in payload]
    if missing:
        raise ReferenceDataError(f"{name} missing keys: {missing}")


def load_reference_data(directory: Path | str | None = None) -> ReferenceData:
    directory = Path(directory) if directory else REFERENCE_DIR

    dry = _read(directory, "dry_endpoints.json")
    _require(dry, ("time_origin", "storage_condition", "sessions"), "dry_endpoints.json")
    if dry["time_origin"] != "FIRST_SENSOR_TIMESTAMP":
        raise ReferenceDataError("dry_endpoints.json has an unexpected time origin")
    if dry["storage_condition"] != "DRY":
        raise ReferenceDataError("dry_endpoints.json must describe DRY storage")
    sessions = dry["sessions"]
    if not isinstance(sessions, list) or len(sessions) != 3:
        raise ReferenceDataError("dry_endpoints.json must contain exactly three sessions")
    endpoints, intervals, seen = [], [], set()
    for entry in sessions:
        _require(entry, ("session_id", "lower_h", "upper_h"), "dry_endpoints.json session")
        session = str(entry["session_id"])
        if session not in SESSIONS:
            raise ReferenceDataError(f"unexpected session in dry references: {session}")
        seen.add(session)
        lower = _finite(entry["lower_h"], f"{session}.lower_h")
        upper = _finite(entry["upper_h"], f"{session}.upper_h")
        if upper <= lower:
            raise ReferenceDataError(f"{session}: upper_h must exceed lower_h")
        if lower <= 0:
            raise ReferenceDataError(f"{session}: lower_h must be positive")
        intervals.append((lower, upper))
        endpoints.append(DryEndpoint(
            session_id=session, lower_h=lower, upper_h=upper, width_h=upper - lower,
            first_sensor_timestamp=entry.get("first_sensor_timestamp"),
            endpoint_source=entry.get("endpoint_source")))
    if seen != set(SESSIONS):
        raise ReferenceDataError(f"dry sessions must be {SESSIONS}, got {sorted(seen)}")

    turnbull = _read(directory, "turnbull_npmle.json")
    _require(turnbull, ("support_intervals", "probability_masses", "convergence"),
             "turnbull_npmle.json")
    support_raw = turnbull["support_intervals"]
    masses_raw = turnbull["probability_masses"]
    if len(support_raw) != len(masses_raw) or not support_raw:
        raise ReferenceDataError("Turnbull support and mass lengths must match and be non-empty")
    support, masses = [], []
    for index, (interval, mass) in enumerate(zip(support_raw, masses_raw)):
        _require(interval, ("lower", "upper"), f"Turnbull support[{index}]")
        lower = _finite(interval["lower"], f"support[{index}].lower")
        upper = _finite(interval["upper"], f"support[{index}].upper")
        if upper <= lower:
            raise ReferenceDataError(f"support[{index}] has upper <= lower")
        support.append((lower, upper))
        masses.append(_finite(mass, f"mass[{index}]"))
    if any(mass < 0 for mass in masses):
        raise ReferenceDataError("Turnbull masses must be non-negative")
    total = sum(masses)
    if abs(total - 1.0) > 1e-9:
        raise ReferenceDataError(f"Turnbull masses sum to {total}, expected 1")
    for left, right in zip(support, support[1:]):
        if right[0] < left[1]:
            raise ReferenceDataError("Turnbull support intervals must be ordered and disjoint")

    weibull = _read(directory, "weibull_a0.json")
    _require(weibull, ("shape", "scale", "model"), "weibull_a0.json")
    shape = _finite(weibull["shape"], "weibull.shape")
    scale = _finite(weibull["scale"], "weibull.scale")
    if shape <= 0 or scale <= 0:
        raise ReferenceDataError("Weibull shape and scale must be positive")

    provenance = _read(directory, "provenance.json")
    _require(provenance, ("research_status", "time_origin", "tvoc_contribution"),
             "provenance.json")
    if provenance["research_status"] != "POST_HOC_EXPLORATORY_DESCRIPTIVE":
        raise ReferenceDataError("provenance research_status must be POST_HOC_EXPLORATORY_DESCRIPTIVE")
    if provenance["tvoc_contribution"] != "NOT_ESTABLISHED":
        raise ReferenceDataError("provenance tvoc_contribution must be NOT_ESTABLISHED")

    return ReferenceData(
        intervals=tuple(intervals), endpoints=tuple(endpoints),
        turnbull_support=tuple(support), turnbull_masses=tuple(masses),
        turnbull_converged=bool(turnbull["convergence"].get("converged", False)),
        weibull_shape=shape, weibull_scale=scale,
        time_origin=dry["time_origin"], research_status=provenance["research_status"],
        provenance=provenance)
